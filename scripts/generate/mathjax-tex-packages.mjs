import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { source } from '@mathjax/src/components/mjs/source.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const generatedDir = path.resolve(__dirname, '../../src/generated')
const generatedFile = path.join(generatedDir, 'mathjax-tex-packages.ts')

// These packages depend on MathJax's asynchronous component loader, which is
// unavailable when linking directly to MathJax from Marp Core's synchronous
// rendering pipeline.
const componentLoaderPackages = new Set(['autoload', 'require'])

const packageNames = [
  'base',
  ...Object.keys(source)
    .filter((name) => name.startsWith('[tex]/'))
    .map((name) => name.slice(6))
    .filter((name) => !componentLoaderPackages.has(name))
    .sort(),
]

const mathjaxDir = path.dirname(
  fileURLToPath(import.meta.resolve('@mathjax/src/package.json')),
)
const texDir = path.join(mathjaxDir, 'mjs/input/tex')

const configurationModules = await Promise.all(
  packageNames.map(async (packageName) => {
    const packageDir = path.join(texDir, packageName)
    const configurationFiles = (await fs.readdir(packageDir)).filter((file) =>
      file.endsWith('Configuration.js'),
    )

    if (configurationFiles.length !== 1) {
      throw new Error(
        `Expected exactly one configuration module for the MathJax TeX package "${packageName}", but found ${configurationFiles.length}.`,
      )
    }

    return `@mathjax/src/mjs/input/tex/${packageName}/${configurationFiles[0]}`
  }),
)

const fontExtensionPackageNames = new Set()

for (const packageName of packageNames) {
  const componentModule = source[`[tex]/${packageName}`]

  if (!componentModule) continue

  const componentSource = await fs.readFile(componentModule, 'utf8')

  for (const match of componentSource.matchAll(
    /fontExtension\([^,]+,\s*['"]([^'"]+)['"]\)/g,
  )) {
    fontExtensionPackageNames.add(match[1])
  }
}

const fontExtensions = await Promise.all(
  [...fontExtensionPackageNames].sort().map(async (packageName) => {
    const moduleName = `@mathjax/${packageName}/mjs/svg.js`
    const moduleSource = await fs.readFile(
      fileURLToPath(import.meta.resolve(moduleName)),
      'utf8',
    )
    const exportName = moduleSource.match(
      /export const (\w+FontExtension)\s*=/,
    )?.[1]

    if (!exportName) {
      throw new Error(
        `Could not find a font extension export from "${moduleName}".`,
      )
    }

    return { exportName, moduleName }
  }),
)

const lines = [
  '// This file is auto-generated by scripts/generate/mathjax-tex-packages.mjs.',
  '// Do not edit manually.',
  '',
  'export const packages = [',
  ...packageNames.map((packageName) => `  ${JSON.stringify(packageName)},`),
  ']',
  '',
  'export const registerMathJaxTexPackages = () => {',
  ...fontExtensions.map(
    ({ exportName, moduleName }) =>
      `  const { ${exportName} } = require(${JSON.stringify(moduleName)}) as typeof import(${JSON.stringify(moduleName)})`,
  ),
  '',
  ...configurationModules.map(
    (moduleName) => `  require(${JSON.stringify(moduleName)})`,
  ),
  '',
  '  return [',
  ...fontExtensions.map(({ exportName }) => `    ${exportName},`),
  '  ]',
  '}',
  '',
]

await fs.mkdir(generatedDir, { recursive: true })
await fs.writeFile(generatedFile, lines.join('\n'))
