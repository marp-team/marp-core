import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { bundledLanguagesInfo } from 'shiki/langs'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const generatedDir = path.resolve(__dirname, '../../src/generated')

const langIds = [...new Set(bundledLanguagesInfo.map(({ id }) => id))].sort()
const languageIds = new Map()

for (const { aliases = [], id } of bundledLanguagesInfo) {
  for (const alias of aliases) languageIds.set(alias, id)
  languageIds.set(id, id)
}

const moduleId = (id) => `__${id.replace(/[^a-zA-Z0-9_$]/g, '_')}`

await fs.mkdir(generatedDir, { recursive: true })
await fs.writeFile(
  path.join(generatedDir, 'shiki-lang-loaders.ts'),
  [
    '// This file is auto-generated by scripts/generate/shiki-lang-loaders.mjs.',
    '// Do not edit manually.',
    '',
    ...langIds.map(
      (id) => `import ${moduleId(id)} from 'shiki/langs/${id}.mjs'`,
    ),
    '',
    'export const langLoaders = {',
    ...langIds.map((id) => `  "${id}": () => ${moduleId(id)},`),
    '} as const',
    '',
  ].join('\n'),
)

await fs.writeFile(
  path.join(generatedDir, 'shiki-lang-lazy-loaders.ts'),
  [
    '// This file is auto-generated by scripts/generate/shiki-lang-loaders.mjs.',
    '// Do not edit manually.',
    '',
    'export const langLoaders = {',
    ...langIds.map(
      (id) =>
        `  ${JSON.stringify(id)}: () => require(${JSON.stringify(`shiki/langs/${id}.mjs`)}).default,`,
    ),
    '} as const',
    '',
  ].join('\n'),
)

await fs.writeFile(
  path.join(generatedDir, 'shiki-language-ids.ts'),
  [
    '// This file is auto-generated by scripts/generate/shiki-lang-loaders.mjs.',
    '// Do not edit manually.',
    '',
    'export const languageIds: Record<string, string> = {',
    ...[...languageIds]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(
        ([alias, id]) => `  ${JSON.stringify(alias)}: ${JSON.stringify(id)},`,
      ),
    '}',
    '',
  ].join('\n'),
)
